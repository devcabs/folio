/**
 * Migration Prompt Formatter
 * Pure, side-effect-free utility for formatting AI migration prompts from pending migration reports.
 * Zero imports from service or context layers.
 */

import type { PendingMigrationReport } from '../types/migration';

export interface PromptFormatterOptions {
  agentHint?: 'claude' | 'cursor' | 'antigravity' | 'generic';
}

/**
 * Formats a copyable, actionable AI migration prompt from a pending migration report.
 */
export function generateAiMigrationPrompt(
  report: PendingMigrationReport,
  _options?: PromptFormatterOptions
): string {
  let md = `# AI Migration Prompt\n\nUpdating from v${report.contentVersionWatermark} → v${report.currentEngineVersion}\n\n`;

  if (report.pendingContentChanges && report.pendingContentChanges.length > 0) {
    report.pendingContentChanges.forEach((change, idx) => {
      md += `## ${idx + 1}. ${change.title}\n\n`;
      md += `**Required:** ${change.required ? 'Yes' : 'No'}\n\n`;
      if (change.affectedEntities && change.affectedEntities.length > 0) {
        md += `**Affected Entities:** ${change.affectedEntities.join(', ')}\n\n`;
      }
      md += `${change.description}\n\n`;
      if (change.migrationPrompt) {
        md += `**Instructions:**\n${change.migrationPrompt}\n\n`;
      }
    });
  }

  md += `<!-- Generated by @devcabs/folio-engine migrationService -->\n<!-- Pending migrations for watermark ${report.contentVersionWatermark} (current: ${report.currentEngineVersion}) -->`;
  return md;
}

