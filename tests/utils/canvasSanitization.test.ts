import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import React from 'react';
import ReactDOMServer from 'react-dom/server';
import {
  AUTHORING_PLACEHOLDERS,
  isAuthoringPlaceholder,
  createDefaultText,
  createDefaultPhoto,
  createDefaultSection,
  createDefaultSubsection,
} from '../../src/utils/canvasDefaults';
import { CanvasText } from '../../src/components/canvas/CanvasText';
import { CanvasPhoto } from '../../src/components/canvas/CanvasPhoto';
import * as developerModeHook from '../../src/hooks/useDeveloperMode';
import type { TextElement, PhotoElement } from '../../src/types/canvas';

describe('Subtask 3.5: Public Editorial Text Placeholder Sanitization', () => {
  beforeEach(() => {
    vi.restoreAllMocks();
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  describe('AUTHORING_PLACEHOLDERS set & isAuthoringPlaceholder helper', () => {
    it('defines the canonical set of factory authoring placeholder strings', () => {
      expect(AUTHORING_PLACEHOLDERS).toBeInstanceOf(Set);
      expect(AUTHORING_PLACEHOLDERS.has('Click Edit to add narrative text for this section.')).toBe(true);
      expect(AUTHORING_PLACEHOLDERS.has('Photo documentation.')).toBe(true);
      expect(AUTHORING_PLACEHOLDERS.has('Milestone initiatives and summary of progress')).toBe(true);
      expect(AUTHORING_PLACEHOLDERS.has('Subsection details and documentation')).toBe(true);
      expect(AUTHORING_PLACEHOLDERS.has('Subsection Title')).toBe(true);
      expect(AUTHORING_PLACEHOLDERS.has('Section Title')).toBe(true);
    });

    it('identifies undefined, null, empty string, and whitespace as placeholders', () => {
      expect(isAuthoringPlaceholder(undefined)).toBe(true);
      expect(isAuthoringPlaceholder(null)).toBe(true);
      expect(isAuthoringPlaceholder('')).toBe(true);
      expect(isAuthoringPlaceholder('   ')).toBe(true);
      expect(isAuthoringPlaceholder('\t\n  ')).toBe(true);
    });

    it('identifies exact and trimmed factory default placeholders', () => {
      expect(isAuthoringPlaceholder('Click Edit to add narrative text for this section.')).toBe(true);
      expect(isAuthoringPlaceholder('  Click Edit to add narrative text for this section.  ')).toBe(true);
      expect(isAuthoringPlaceholder('Photo documentation.')).toBe(true);
      expect(isAuthoringPlaceholder('Milestone initiatives and summary of progress')).toBe(true);
      expect(isAuthoringPlaceholder('Subsection details and documentation')).toBe(true);
      expect(isAuthoringPlaceholder('Subsection Title')).toBe(true);
      expect(isAuthoringPlaceholder('Section Title')).toBe(true);
    });

    it('recognizes factory defaults generated by canvasDefaults factory functions', () => {
      const defaultText = createDefaultText('node-alpha');
      const defaultPhoto = createDefaultPhoto('node-alpha');
      const defaultSection = createDefaultSection(0, 'node-alpha');
      const defaultSubsection = createDefaultSubsection('node-alpha');

      expect(isAuthoringPlaceholder(defaultText.content)).toBe(true);
      expect(isAuthoringPlaceholder(defaultPhoto.caption)).toBe(true);
      expect(isAuthoringPlaceholder(defaultSection.title)).toBe(true);
      expect(isAuthoringPlaceholder(defaultSection.subtitle)).toBe(true);
      expect(isAuthoringPlaceholder(defaultSubsection.title)).toBe(true);
      expect(isAuthoringPlaceholder(defaultSubsection.subtitle)).toBe(true);
    });

    it('returns false for customized authoring and editorial copy', () => {
      expect(isAuthoringPlaceholder('We achieved 98% graduation rate across all programs.')).toBe(false);
      expect(isAuthoringPlaceholder('Photographic evidence of the new science complex.')).toBe(false);
      expect(isAuthoringPlaceholder('Institutional Growth & Governance')).toBe(false);
      expect(isAuthoringPlaceholder('Phase 1 Completion Report')).toBe(false);
      expect(isAuthoringPlaceholder('A')).toBe(false);
    });
  });

  describe('CanvasText Public Sanitization Gate', () => {
    it('suppresses rendering completely (renders null) in public mode when text contains factory placeholder', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const defaultText = createDefaultText('node-beta');
      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: defaultText,
          nodeId: 'node-beta',
        })
      );

      expect(html).toBe('');
    });

    it('suppresses rendering completely in public mode when content is empty or whitespace', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const emptyText: TextElement = {
        id: 'text-empty',
        type: 'text',
        pointId: 'node.beta.text.empty',
        content: '   ',
      };
      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: emptyText,
          nodeId: 'node-beta',
        })
      );

      expect(html).toBe('');
    });

    it('renders custom narrative copy cleanly in public mode without suppression', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const customText: TextElement = {
        id: 'text-custom',
        type: 'text',
        pointId: 'node.beta.text.custom',
        content: 'We achieved 98% graduation rate across all programs in 2026.',
      };
      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: customText,
          nodeId: 'node-beta',
        })
      );

      expect(html).toContain('We achieved 98% graduation rate across all programs in 2026.');
      expect(html).not.toContain('devPlaceholderText');
    });

    it('renders default placeholder text with subdued styling in Developer Mode so coordinators can select and edit', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: true,
        isDesktop: true,
      } as any);

      const defaultText = createDefaultText('node-beta');
      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: defaultText,
          nodeId: 'node-beta',
        })
      );

      expect(html).toContain('Click Edit to add narrative text for this section.');
      expect(html).toContain('devPlaceholderText');
    });

    it('respects isDevMode prop override when provided', () => {
      // Hook returns dev mode = true, but prop passes false
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: true,
        isDesktop: true,
      } as any);

      const defaultText = createDefaultText('node-beta');
      const htmlPublic = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: defaultText,
          nodeId: 'node-beta',
          isDevMode: false,
        })
      );

      expect(htmlPublic).toBe('');

      // Hook returns dev mode = false, but prop passes true
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const htmlDev = ReactDOMServer.renderToString(
        React.createElement(CanvasText, {
          element: defaultText,
          nodeId: 'node-beta',
          isDevMode: true,
        })
      );

      expect(htmlDev).toContain('Click Edit to add narrative text for this section.');
    });
  });

  describe('CanvasPhoto Public Caption Sanitization Gate', () => {
    const basePhoto: PhotoElement = {
      id: 'photo-alpha',
      type: 'photo',
      pointId: 'node.alpha.photo.photo-alpha',
      src: 'https://images.unsplash.com/photo-1544717305-2782549b5136',
      alt: 'Documentation photo',
      caption: 'Photo documentation.',
    };

    it('suppresses placeholder caption in public mode leaving caption markup absent', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasPhoto, {
          element: basePhoto,
          nodeId: 'node-alpha',
        })
      );

      // Must render the image
      expect(html).toContain('img');
      // Must NOT render the default authoring caption
      expect(html).not.toContain('Photo documentation.');
      expect(html).not.toContain('photoCaption');
    });

    it('renders genuine custom photo caption in public mode', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const customPhoto: PhotoElement = {
        ...basePhoto,
        caption: 'Panoramic view of the academic research quad.',
      };

      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasPhoto, {
          element: customPhoto,
          nodeId: 'node-alpha',
        })
      );

      expect(html).toContain('Panoramic view of the academic research quad.');
      expect(html).toContain('photoCaption');
    });

    it('preserves placeholder caption in Developer Mode for editorial visibility', () => {
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: true,
        isDesktop: true,
      } as any);

      const html = ReactDOMServer.renderToString(
        React.createElement(CanvasPhoto, {
          element: basePhoto,
          nodeId: 'node-alpha',
        })
      );

      expect(html).toContain('Photo documentation.');
      expect(html).toContain('photoCaption');
    });

    it('respects isDevMode prop override on CanvasPhoto', () => {
      // Context is dev mode = true, but prop is false
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: true,
        isDesktop: true,
      } as any);

      const htmlPublic = ReactDOMServer.renderToString(
        React.createElement(CanvasPhoto, {
          element: basePhoto,
          nodeId: 'node-alpha',
          isDevMode: false,
        })
      );
      expect(htmlPublic).not.toContain('Photo documentation.');

      // Context is dev mode = false, but prop is true
      vi.spyOn(developerModeHook, 'useDeveloperMode').mockReturnValue({
        isDevMode: false,
        isDesktop: true,
      } as any);

      const htmlDev = ReactDOMServer.renderToString(
        React.createElement(CanvasPhoto, {
          element: basePhoto,
          nodeId: 'node-alpha',
          isDevMode: true,
        })
      );
      expect(htmlDev).toContain('Photo documentation.');
    });
  });
});
